    def _redraw_animated(self):
        self.canvas.after.clear()
        g = self._geo
        if g is None: return
        with self.canvas.after:
            if self._knife_label:
                self._knife_label.text = f"{self.active_knives}/{self.total_knives} ножей"
            if self.selected_node:
                rects = self._get_node_rects(g)
                if self.selected_node in rects:
                    nx, ny, nw, nh = rects[self.selected_node]
                    Color(1, 1, 0.3, 0.9)
                    Line(rounded_rectangle=(nx, ny, nw, nh, dp(4)), width=3)
            if self.problem_node:
                for node_name, (nx, ny, nw, nh) in self._get_node_rects(g).items():
                    if node_name == self.problem_node:
                        if self.blink: Color(1, 0.2, 0.2, 0.9)
                        else: Color(1, 0.6, 0.6, 0.4)
                        Line(rounded_rectangle=(nx, ny, nw, nh, dp(4)), width=3)
            if self.machine_running:
                self._draw_roll_dots(g)
                self._draw_module_dots(g)
                self._draw_glue_anim(g)
                self._draw_dryer_steam(g)
                self._draw_bridge_paper(g)
            self._draw_knife_vertical(g["waste_x"], g["node_y"], g["node_w"], g["node_h"],
                                      self.problem_active, color=(1, 0.4, 0.4, 1))
            self._draw_knife_vertical(g["cutoff_x"], g["node_y"], g["node_w"], g["node_h"],
                                      self.machine_running, color=(0.5, 0.8, 1, 1))
            self._draw_slitter_knives(g["slitter_x"], g["node_y"], g["node_w"], g["node_h"])
