    def _game_tick(self, dt):
        if not self.running: return
        self.action_count += 1
        self.game_time += GAME_TICK
        if (self.machine.running and self.active_problem is None and
                self.active_breakdown is None):
            self.machine.produce()
            if random.random() < 0.08:
                self.log("Агрегат работает...", 'work')
            if self.current_order and random.random() < 0.1:
                self.current_order.update_progress(5)
            if self.current_order and random.random() < 0.15:
                self.manual_pallet_loading()
        if random.random() < 0.05:
            self.create_order()
            self.last_order_time = self.game_time
        if random.random() < 0.02:
            self.cancel_order()
        if self.active_problem is None and self.active_breakdown is None:
            base_risk = 0.10
            if self.selected_role == "Бригадир" and self.machine.running:
                avg_mod = sum(self._get_problem_risk_modifier(s)
                              for s in PROBLEMS.keys()) / len(PROBLEMS)
                risk = base_risk * avg_mod
            else:
                risk = base_risk
            if random.random() < risk:
                self._spawn_problem()
        if self.active_problem is None and self.active_breakdown is None:
            if random.random() < 0.03:
                self._spawn_breakdown()
        self._check_problem_timeout(dt)
        self._check_breakdown_timeout(dt)
        self._check_triggers()
        if self.master_ai:
            self.master_ai.maybe_tell_story()
        if self.action_count >= BRIGADE_CHANGE_INTERVAL:
            self.change_brigade()
        if random.random() < 0.005:
            self.log(CHUFYR_PHRASE, 'chufyr')
            self.machine.stop()
            self.schedule_restart(2)
        if random.random() < 0.03:
            if self.karshik.deliver_roll() == "битый":
                self.log(f"[Карщик {self.karshik.name}] Привёз БИТЫЙ ролик!", 'defect')
                self.machine.stop()
                self.schedule_restart(1.5)
        if random.random() < 0.05:
            worker = random.choice(["лицевик", "модульщик", "релёвщик", "хвостовик"])
            self.log(f"{worker} ушёл курить", 'smoke')
        if random.random() < 0.20:
            self.log(f"Наушники: {self.get_random_chatter()}", 'headset')
        if random.random() < 0.02:
            glue = self.klevar.make_glue()
            self.machine.glue_level = min(100, self.machine.glue_level + glue)
            self.log(f"[Клеевар {self.klevar.name}] +{glue}% клея", 'klevar')
        self.update_status()
        self._update_indicators()

    def _update_indicators(self):
        self._update_indicator(self.glue_indicator, self.machine.glue_level)
        self._update_indicator(self.wear_indicator, self.machine.wear)

    def get_random_chatter(self):
        available = [p for p in HEADSET_CHATTER if p != self.last_chatter]
        if not available:
            available = HEADSET_CHATTER
        phrase = random.choice(available)
        self.last_chatter = phrase
        return phrase

    def update_status(self):
        status = ""
        if self.current_order:
            status += (f"Заказ #{self.current_order.id}: "
                       f"{self.current_order.info_str()}\n"
                       f"Прогресс: {self.current_order.progress}%\n")
        else:
            status += "Нет активных заказов\n"
        status += (f"Устранено: {self.operator.problems_solved} | "
                   f"Провалено: {self.operator.problems_failed} | "
                   f"Поломок: {self.operator.breakdowns_count} | "
                   f"Тест: +{self.operator.quiz_correct}/"
                   f"-{self.operator.quiz_wrong}")
        self.status_label.text = status


