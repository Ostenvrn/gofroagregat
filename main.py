class Order:
    def __init__(self, order_id, order_type, quantity, width, trim, cut_count, length):
        self.id = order_id
        self.type = order_type
        self.quantity = quantity
        self.width = width
        self.trim = trim
        self.cut_count = cut_count
        self.length = length
        self.status = "Новый"
        self.progress = 0
        self._lock = threading.Lock()

    def update_progress(self, amount):
        with self._lock:
            self.progress = min(100, self.progress + amount)
            if self.progress >= 100:
                self.status = "Готов"
                return True
            return False

    def get_active_knives(self):
        return 2 + self.cut_count

    def get_cut_speed_factor(self):
        return max(0.4, min(2.0, 800.0 / self.length))

    def info_str(self):
        return (f"{self.type} {self.width}мм, обрезь {self.trim}мм, "
                f"резов {self.cut_count}, длина {self.length}мм")


