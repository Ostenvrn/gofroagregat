class CorrugatorMachine:
    def __init__(self):
        self.wear = 0
        self.glue_level = 100
        self.paper_level = 100
        self.running = False
        self._lock = threading.Lock()

    def start(self):
        with self._lock:
            if self.wear < 100 and self.paper_level > 0 and self.glue_level > 0:
                self.running = True
                return True
            return False

    def stop(self):
        with self._lock: self.running = False

    def produce(self):
        with self._lock:
            if not self.running: return
            self.wear = min(100, self.wear + random.randint(0, 1))
            self.paper_level = max(0, self.paper_level - random.randint(1, 2))
            self.glue_level = max(0, self.glue_level - random.randint(1, 2))
            if self.paper_level <= 0 or self.glue_level <= 0:
                self.running = False


