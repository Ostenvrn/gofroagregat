    def _check_problem_timeout(self, dt):
        if self.active_problem is None: return
        self.problem_timer += dt
        if self.problem_timer >= PROBLEM_AUTO_RESOLVE_TIME:
            success = random.random() > PROBLEM_FAIL_CHANCE
