class AggregateScheme(FloatLayout):
    def __init__(self, app, **kwargs):
        super().__init__(**kwargs)
        self.app = app
        self.machine_running = False
        self.problem_active = False
        self.anim_phase = 0
        self.blink = 0
        self.active_knives = 3
        self.total_knives = 9
        self.cut_speed_factor = 1.0
        self.problem_node = None
        self.selected_node = None
        self._geo = None
        self._knife_label = None
        self.bind(pos=self._on_layout, size=self._on_layout)

    def _on_layout(self, *args):
        if self.width > 100 and self.height > 100:
            self._layout_static()

    def set_problem(self, node_name):
        if self.problem_node != node_name:
            self.problem_node = node_name
            self.problem_active = True
            self._redraw_animated()

    def clear_problem(self):
        if self.problem_node is not None:
            self.problem_node = None
            self.problem_active = False
            self._redraw_animated()

    def set_order_params(self, active_knives, cut_speed_factor):
        self.active_knives = max(2, min(self.total_knives, active_knives))
        self.cut_speed_factor = max(0.4, min(2.0, cut_speed_factor))

    def animate_step(self, dt):
        if self.problem_active:
            self.anim_phase = (self.anim_phase + 1) % 12
            if self.anim_phase % 2 == 0:
                return
        else:
            self.anim_phase = (self.anim_phase + 1) % 12
        self.blink = 1 - self.blink
        self._redraw_animated()

    def on_touch_down(self, touch):
        if self.collide_point(*touch.pos):
            node = self._hit_test_node(touch.x, touch.y)
            if node:
                self.selected_node = node
                self._redraw_animated()
                self.app.show_node_info(node)
                return True
            else:
                if self.selected_node:
                    self.selected_node = None
                    self._redraw_animated()
        return super().on_touch_down(touch)

    def _hit_test_node(self, touch_x, touch_y):
        if self._geo is None: return None
        rects = self._get_node_rects(self._geo)
        for name, (nx, ny, nw, nh) in reversed(list(rects.items())):
            if nx <= touch_x <= nx + nw and ny <= touch_y <= ny + nh:
                return name
        return None

    def _layout_static(self):
        for lbl in self.children[:]:
            if isinstance(lbl, Label):
                self.remove_widget(lbl)
        w = self.width; h = self.height
