    def create_order(self):
        with self.orders_lock:
            self.order_counter += 1
            order_type = random.choice(ORDER_TYPES)
            params = ORDER_PARAMS[order_type]
            width = random.randint(*params["width_range"])
            trim = random.randint(*params["trim_range"])
            cut_count = random.randint(*params["cut_count_range"])
            length = random.randint(*params["length_range"])
            quantity = random.randint(100, 1000)
            order = Order(self.order_counter, order_type, quantity, width, trim, cut_count, length)
            self.orders.append(order)
            if not self.current_order:
                self.current_order = order
                order.status = "В работе"
                self.log(f"НОВЫЙ ЗАКАЗ #{order.id}: {order.info_str()}", 'order')
                self.log(f"[Планировщик] Заказ принят в работу", 'planner')
            else:
                self.log(f"Заказ #{order.id} в очередь: {order.info_str()}", 'info')

    def cancel_order(self):
        with self.orders_lock:
            if not self.orders: return
            order = random.choice(self.orders)
            if order.status != "Отгружен":
                order.status = "Отменён"
                if order in self.orders: self.orders.remove(order)
                self.log(f"ЗАКАЗ #{order.id} ОТМЕНЁН!", 'cancel')
                if order == self.current_order:
                    self.current_order = self.orders[0] if self.orders else None
                    if self.current_order:
                        self.current_order.status = "В работе"

